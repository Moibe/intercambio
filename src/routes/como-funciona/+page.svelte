<div class="pagina">
  <h1>Cómo funciona</h1>
  <p class="sub">Tres pasos, sin cuentas ni contraseñas.</p>

  <div class="card">
    <h2>1. El organizador crea el grupo</h2>
    <p class="tenue">
      Pone el nombre del grupo y el suyo. Recibe un <strong>link de organizador</strong> que debe
      guardar: es la única forma de volver al panel.
    </p>
  </div>
  <div class="card">
    <h2>2. Agrega a la familia y las exclusiones</h2>
    <p class="tenue">
      Cada persona agregada obtiene su <strong>link personal</strong>. Las exclusiones definen quién no
      puede regalarle a quién (parejas, papás e hijos…), en un sentido o en ambos.
    </p>
  </div>
  <div class="card">
    <h2>3. Sortea y reparte los links</h2>
    <p class="tenue">
      El sorteo respeta las exclusiones y, si el grupo ya tuvo un intercambio antes,
      <strong>evita que te toque la misma persona que la vez pasada</strong>. Cada quien abre su link y
      destapa a quién le regala. El organizador ve quién ya lo abrió, pero no a quién le tocó a nadie.
    </p>
  </div>
</div>
